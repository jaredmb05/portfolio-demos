// Writes apps/shared/config.js from .env, so no keys or PINs live in the code or in git.
// Usage: node scripts/write-config.mjs   (reads .env next to this repo's README; see .env.example)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REQUIRED = ['FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID', 'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID', 'FIREBASE_APP_ID', 'MANAGER_PIN'];

// KEY=value lines; blank lines and # comments are skipped; surrounding quotes are removed
function parseEnv(text) {
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return env;
}

let text;
try { text = readFileSync(join(root, '.env'), 'utf8'); }
catch { console.error('No .env found. Copy .env.example to .env and fill it in.'); process.exit(1); }
const env = parseEnv(text);
const missing = REQUIRED.filter(k => !env[k]);
if (missing.length) { console.error(`.env is missing: ${missing.join(', ')}`); process.exit(1); }

const config = {
  firebase: {
    apiKey: env.FIREBASE_API_KEY,
    authDomain: env.FIREBASE_AUTH_DOMAIN,
    projectId: env.FIREBASE_PROJECT_ID,
    storageBucket: env.FIREBASE_STORAGE_BUCKET,
    messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID,
    appId: env.FIREBASE_APP_ID,
  },
  managerPin: env.MANAGER_PIN,
};
const body = `// Generated by scripts/write-config.mjs from .env. Do not edit or commit.\nwindow.APP_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
writeFileSync(join(root, 'apps/shared/config.js'), body);   // both apps load ../shared/config.js
console.log('wrote apps/shared/config.js');
